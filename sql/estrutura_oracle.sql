-- MegaFarma - execute no Oracle SQL Developer APENAS se as tabelas ainda nao existirem.
-- Ordem importante: tabelas principais antes das tabelas com foreign key.
CREATE TABLE DDD_CLIENTES (
  CODIGO NUMBER PRIMARY KEY,
  NOME VARCHAR2(100 BYTE),
  CPF VARCHAR2(20 BYTE),
  EMAIL VARCHAR2(50 BYTE),
  DATA_DE_NASCIMENTO DATE
);

CREATE TABLE DDD_REMEDIOS (
  CODIGO NUMBER PRIMARY KEY,
  NOME VARCHAR2(100 BYTE),
  PRECO NUMBER(6,2),
  DATA_DE_FABRICACAO DATE,
  DATA_DE_VALIDADE DATE
);

CREATE TABLE DDD_VENDAS (
  CODIGO NUMBER PRIMARY KEY,
  DATA_DA_VENDA DATE,
  CODCLIENTE NUMBER,
  CONSTRAINT FK_MEGAFARMA_VENDA_CLIENTE FOREIGN KEY (CODCLIENTE) REFERENCES DDD_CLIENTES(CODIGO)
);

CREATE TABLE DDD_ITENSVENDIDOS (
  CODVENDA NUMBER,
  CODREMEDIO NUMBER,
  QUANTIDADE NUMBER,
  CONSTRAINT PK_MEGAFARMA_ITENS PRIMARY KEY (CODVENDA, CODREMEDIO),
  CONSTRAINT FK_MEGAFARMA_ITEM_VENDA FOREIGN KEY (CODVENDA) REFERENCES DDD_VENDAS(CODIGO),
  CONSTRAINT FK_MEGAFARMA_ITEM_REMEDIO FOREIGN KEY (CODREMEDIO) REFERENCES DDD_REMEDIOS(CODIGO)
);
